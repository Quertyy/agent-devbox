#!/usr/bin/env python3
"""Render docs/configuration.md from the roles' argument specs and defaults.

    python3 tools/gen-config-doc.py           # rewrite docs/configuration.md
    python3 tools/gen-config-doc.py --check   # fail if it is out of date (CI)
"""
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "configuration.md"
# Roles whose argument specs are documented; common's settings are grouped by
# the "# --- Title" comments of its defaults file.
SPEC_ROLES = ["common", "iron_proxy", "monitoring"]
ROLE_TITLES = {"iron_proxy": "iron-proxy (advanced)", "monitoring": "Monitoring (advanced)"}


def load(path):
    return yaml.safe_load(path.read_text()) or {}


def fmt_default(value):
    if value is None:
        return ""
    if isinstance(value, str):
        if "{{" in value:
            return "computed"
        return f"`{value}`" if value else '`""`'
    text = yaml.safe_dump(value, default_flow_style=True, width=1000).strip()
    text = text.removesuffix("...").strip()
    return f"`{text}`" if len(text) <= 160 else "see defaults"


def fmt_type(spec):
    t = spec.get("type", "str")
    if t == "list" and spec.get("elements"):
        t = f"list of {spec['elements']}"
    if spec.get("choices"):
        t += " (" + " \\| ".join(str(c) for c in spec["choices"]) + ")"
    return t


def section_titles():
    """Map setting -> section title from '# --- Title' comments in defaults."""
    titles, current = {}, "General"
    for line in (ROOT / "roles/common/defaults/main.yml").read_text().splitlines():
        if line.startswith("# --- "):
            current = line[6:].strip()
        elif line and not line.startswith(("#", " ")) and ":" in line:
            titles[line.split(":", 1)[0]] = current
    return titles


def render():
    titles = section_titles()
    lines = [
        "# Configuration reference",
        "",
        "<!-- Generated by tools/gen-config-doc.py from roles/*/meta/argument_specs.yml",
        "     and roles/*/defaults/main.yml. Do not edit by hand. -->",
        "",
        "All settings go in your host file (`inventory/host_vars/<host>.yml`), see",
        "[config.example.yml](../config.example.yml). They are validated when the",
        "playbook starts: wrong types, unknown sub-keys and invalid choices are",
        "refused, and unknown `devbox_*` names are reported (typos).",
        "",
    ]
    for role in SPEC_ROLES:
        specs = load(ROOT / f"roles/{role}/meta/argument_specs.yml")["argument_specs"]["main"]["options"]
        defaults = load(ROOT / f"roles/{role}/defaults/main.yml")
        groups = {}
        for name, spec in specs.items():
            title = titles.get(name, "Advanced") if role == "common" else ROLE_TITLES[role]
            groups.setdefault(title, []).append((name, spec))
        for title, items in groups.items():
            lines += [f"## {title}", "", "| Setting | Type | Default | Description |", "|---|---|---|---|"]
            for name, spec in items:
                default = "**required**" if spec.get("required") else fmt_default(defaults.get(name))
                desc = " ".join(str(spec.get("description", "")).split())
                if spec.get("options"):
                    subs = "".join(
                        f"<br>• `{k}` ({fmt_type(v)}{', required' if v.get('required') else ''})"
                        + (f": {' '.join(str(v['description']).split())}" if v.get("description") else "")
                        for k, v in spec["options"].items())
                    desc += f"<br>Fields:{subs}"
                lines.append(f"| `{name}` | {fmt_type(spec)} | {default} | {desc.replace('|', '\\|')} |")
            lines.append("")
    presets = load(ROOT / "roles/iron_proxy/vars/main.yml")["iron_proxy_presets"]
    default_presets = load(ROOT / "roles/common/defaults/main.yml")["devbox_allow_presets"]
    lines += ["## Presets", "",
              "Enable them with `devbox_allow_presets`. **Bold** ones are enabled by default.",
              "Methods are listed when a preset is restricted (package registries are read-only).", "",
              "| Preset | Hosts |", "|---|---|"]
    for name, rules in presets.items():
        hosts = []
        for r in rules:
            target = r.get("host") or r.get("cidr")
            extra = []
            if r.get("methods"):
                extra.append("/".join(r["methods"]))
            if r.get("paths"):
                extra.append(", ".join(r["paths"]))
            item = f"`{target}`" + (f" ({'; '.join(extra)})" if extra else "")
            if item not in hosts:
                hosts.append(item)
        label = f"**{name}**" if name in default_presets else name
        lines.append(f"| {label} | {', '.join(hosts)} |")
    lines.append("")
    return "\n".join(lines)


def main():
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit("docs/configuration.md is out of date: run python3 tools/gen-config-doc.py")
        return
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
